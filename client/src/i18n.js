export function getText(language, path, vars = {}) {
  const source = translations[language] || translations.en;
  const value = path.split('.').reduce((acc, key) => acc?.[key], source);
  if (typeof value === 'function') return value(...Object.values(vars));
  if (typeof value === 'string') return value;
  const fallback = path.split('.').reduce((acc, key) => acc?.[key], translations.en);
  if (typeof fallback === 'function') return fallback(...Object.values(vars));
  return fallback || path;
}
